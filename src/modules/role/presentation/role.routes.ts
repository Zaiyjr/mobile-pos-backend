import { Router } from "express";
import { authorizeRoles } from "../../../shared/presentation/middlewares/auth.js";
import { RoleRepositoryPg } from "../infrastructure/role.repository.js";
import { RoleService } from "../application/role.service.js";
import { RoleController } from "./role.controller.js";
const repo = new RoleRepositoryPg();
const service = new RoleService(repo);
const controller = new RoleController(service);
export const roleRouter = Router();
roleRouter.post("/", authorizeRoles("ADMIN"), controller.create);
roleRouter.get("/", controller.getAll);
roleRouter.get("/:id", controller.getById);
roleRouter.put("/:id", authorizeRoles("ADMIN"), controller.update);
roleRouter.delete("/:id", authorizeRoles("ADMIN"), controller.delete);
